package com.example.hatua_app

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.util.Base64
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Encrypts HATUA's private goals with one AES-256-GCM key held in the Android Keystore.
 *
 * Deliberately simple (replaces flutter_secure_storage, whose RSA key-wrapping path failed on a
 * pilot phone): no RSA, no self-signed certificates, no hidden JCA providers, and no user
 * authentication, so reading goals never triggers a fingerprint/PIN prompt. The key never
 * leaves the Keystore; app backups are disabled in the manifest, so ciphertext and key stay on
 * this device. A fresh random 96-bit IV is generated by the Keystore for every encryption.
 *
 * Blob format: "v1:<base64 iv>:<base64 ciphertext+tag>".
 */
object GoalVault {
    private const val KEYSTORE = "AndroidKeyStore"
    private const val ALIAS = "hatua.goals.aesgcm.v1"
    private const val TRANSFORMATION = "AES/GCM/NoPadding"
    private const val TAG_BITS = 128
    private const val PREFIX = "v1"

    @Synchronized
    private fun key(): SecretKey {
        val keyStore = KeyStore.getInstance(KEYSTORE).apply { load(null) }
        (keyStore.getKey(ALIAS, null) as? SecretKey)?.let { return it }
        val generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, KEYSTORE)
        generator.init(
            KeyGenParameterSpec.Builder(ALIAS, KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT)
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(256)
                .setUserAuthenticationRequired(false)
                .build(),
        )
        return generator.generateKey()
    }

    fun encrypt(plainText: String): String {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, key())
        val sealed = cipher.doFinal(plainText.toByteArray(Charsets.UTF_8))
        return listOf(PREFIX, b64(cipher.iv), b64(sealed)).joinToString(":")
    }

    fun decrypt(blob: String): String {
        val parts = blob.split(":")
        require(parts.size == 3 && parts[0] == PREFIX) { "Unrecognised vault blob format" }
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.DECRYPT_MODE, key(), GCMParameterSpec(TAG_BITS, unb64(parts[1])))
        return String(cipher.doFinal(unb64(parts[2])), Charsets.UTF_8)
    }

    @Synchronized
    fun deleteKey() {
        val keyStore = KeyStore.getInstance(KEYSTORE).apply { load(null) }
        if (keyStore.containsAlias(ALIAS)) keyStore.deleteEntry(ALIAS)
    }

    private fun b64(bytes: ByteArray): String = Base64.encodeToString(bytes, Base64.NO_WRAP)

    private fun unb64(text: String): ByteArray = Base64.decode(text, Base64.NO_WRAP)
}
